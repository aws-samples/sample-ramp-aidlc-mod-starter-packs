// The catalogue outputs, relative to the repository root. The README block is
// written only when both markers exist.
export const SKILLS_CATALOG = 'skills/README.md'
export const WORKFLOWS_CATALOG = 'workflows/README.md'
export const ROOT_README = 'README.md'
export const PACKS_BLOCK_START = '<!-- RAMP:CATALOG packs START -->'
export const PACKS_BLOCK_END = '<!-- RAMP:CATALOG packs END -->'

// Base instructions and variants, in the new layout first and the current one
// second. Both are read, so the catalogue keeps working across the move.
const WORKFLOW_BASE_DIRS = ['workflows/base', 'common/instructions']
const WORKFLOW_VARIANT_DIRS = ['workflows/variants', 'workflow-overlays']
// Directory names in skills/ that are never skills.
const RESERVED_SKILL_SLUGS = new Set(['ramp', 'README.md', 'taxonomy'])
const FRONTMATTER = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/
const GENERATED_NOTICE =
  '<!-- Generated by `ramp-pack catalog --write`. Do not edit by hand. -->'
const NOT_DECLARED = 'not declared'

function compareText(left, right) {
  if (left < right) return -1
  if (left > right) return 1
  return 0
}

function toPosix(path) {
  return path.split(sep).join('/')
}

function repoPath(repoRoot, absolutePath) {
  const path = relative(repoRoot, absolutePath)
  if (path === '' || path.startsWith('..') || isAbsolute(path)) {
    throw new Error(`catalog input is outside the repository: ${absolutePath}`)
  }
  return toPosix(path)
}

function isDirectory(path) {
  try {
    const status = lstatSync(path)
    return status.isDirectory() && !status.isSymbolicLink()
  } catch (error) {
    if (error.code === 'ENOENT') return false
    throw error
  }
}

function isFile(path) {
  try {
    const status = lstatSync(path)
    return status.isFile() && !status.isSymbolicLink()
  } catch (error) {
    if (error.code === 'ENOENT') return false
    throw error
  }
}

function listDirectoryNames(directory) {
  if (!isDirectory(directory)) return []
  return readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort(compareText)
}

function readFrontmatter(path, label) {
  const raw = readFileSync(path, 'utf8')
  const match = raw.match(FRONTMATTER)
  if (!match) return {}
  let value
  try {
    value = parse(match[1])
  } catch (error) {
    throw new Error(`${label} has invalid YAML frontmatter: ${error.message}`)
  }
  if (value === null || value === undefined) return {}
  if (typeof value !== 'object' || Array.isArray(value)) {
    throw new Error(`${label} frontmatter must be an object`)
  }
  return value
}

function collapse(text) {
  return typeof text === 'string' ? text.replace(/\s+/g, ' ').trim() : ''
}

const ABBREVIATION = /(?:^|[\s(])(?:e\.g|i\.e|etc|vs|cf|approx)\.$/i

// The first sentence of a description: text up to a ., ! or ? that ends a
// word and is followed by the end or by a capital letter, skipping common
// abbreviations such as "e.g." and "vs.".
export function firstSentence(text) {
  const value = collapse(text)
  const boundary = /[.!?](?=\s|$)/g
  let match
  while ((match = boundary.exec(value)) !== null) {
    const end = match.index + 1
    const sentence = value.slice(0, end)
    if (ABBREVIATION.test(sentence)) continue
    const next = value.slice(end).trimStart()
    if (next === '' || /^[A-Z0-9"'`([]/.test(next)) return sentence
  }
  return value
}

function taxonomyLists(taxonomy) {
  return Object.fromEntries(
    CLASSIFICATION_FACETS.map((facet) => [facet, [...taxonomy[facet].values()]]),
  )
}

// Orders taxonomy ids by display order, then id, and rejects unknown values.
function orderedFacetValues(taxonomy, facet, values, label) {
  const unique = [...new Set(values)]
  for (const value of unique) {
    if (!taxonomy[facet].has(value)) {
      throw new Error(`${label} ${facet} value is not in schemas/taxonomy.yaml: ${value}`)
    }
  }
  const order = [...taxonomy[facet].keys()]
  return unique.sort((left, right) => order.indexOf(left) - order.indexOf(right))
}

function readVariants(repoRoot) {
  const variants = []
  const seen = new Map()
  for (const directory of WORKFLOW_VARIANT_DIRS) {
    const root = join(repoRoot, directory)
    if (!isDirectory(root)) continue
    const files = readdirSync(root, { withFileTypes: true })
      .filter((entry) => entry.isFile() && entry.name.endsWith('.md') && entry.name !== 'README.md')
      .map((entry) => entry.name)
      .sort(compareText)
    for (const file of files) {
      const path = `${directory}/${file}`
      const metadata = readFrontmatter(join(root, file), `workflow variant ${path}`)
      const id = typeof metadata.id === 'string' ? metadata.id : basename(file, '.md')
      if (seen.has(id)) {
        throw new Error(`workflow variant ${id} is defined twice: ${seen.get(id)} and ${path}`)
      }
      seen.set(id, path)
      variants.push({
        id,
        title: collapse(metadata.title) || id,
        instruction: collapse(metadata.instruction ?? metadata.target) || null,
        whenToUse: collapse(metadata.whenToUse ?? metadata.purpose),
        aliases: Array.isArray(metadata.aliases) ? metadata.aliases.map(String) : [],
        path,
        file,
      })
    }
  }
  return variants
}

function readBaseInstructions(repoRoot) {
  const base = new Map()
  for (const directory of WORKFLOW_BASE_DIRS) {
    const root = join(repoRoot, directory)
    if (!isDirectory(root)) continue
    const files = readdirSync(root, { withFileTypes: true })
      .filter((entry) => entry.isFile() && entry.name.endsWith('.md') && entry.name !== 'README.md')
      .map((entry) => entry.name)
      .sort(compareText)
    for (const file of files) {
      const path = `${directory}/${file}`
      if (base.has(file)) {
        throw new Error(`base instruction ${file} is defined twice: ${base.get(file)} and ${path}`)
      }
      base.set(file, path)
    }
  }
  return base
}

// Maps a pack's variant selection to variant ids. workflow.variants holds ids
// or aliases (after T13); workflow.overlays holds file names (today).
function selectedVariantIds(manifest, variants, packName) {
  const selected = manifest.workflow?.variants ?? manifest.workflow?.overlays ?? []
  return selected.map((value) => {
    const name = String(value)
    const id = name.endsWith('.md') ? name.slice(0, -3) : name
    const variant = variants.find(
      (candidate) =>
        candidate.id === id || candidate.file === name || candidate.aliases.includes(id),
    )
    if (!variant) throw new Error(`pack ${packName} selects unknown workflow variant: ${name}`)
    return variant.id
  })
}

function packSkillNames(packDir, manifest) {
  if (Array.isArray(manifest.skills)) return [...manifest.skills]
  // The legacy value "all" means every directory in the pack-local skills/.
  return listDirectoryNames(join(packDir, 'skills'))
}

function readPacks(repoRoot, taxonomy, variants, base) {
  const packsRoot = join(repoRoot, 'packs')
  const adapterOrder = listAdapterIds()
  const sortTools = (tools) =>
    [...tools].sort((left, right) => adapterOrder.indexOf(left) - adapterOrder.indexOf(right))

  return listDirectoryNames(packsRoot)
    .filter((directory) => isFile(join(packsRoot, directory, 'pack.yaml')))
    .map((directory) => {
      const packDir = join(packsRoot, directory)
      const manifest = loadManifest(packDir)
      const name = manifest.name
      const declaredUseCases = manifest.catalog?.useCases ?? []
      const useCases = orderedFacetValues(taxonomy, 'useCases', declaredUseCases, `pack ${name}`)
      const outcome =
        manifest.catalog?.outcome ??
        (declaredUseCases.length > 0
          ? taxonomy.useCases.get(declaredUseCases[0]).outcome
          : null)
      return {
        name,
        directory,
        packDir,
        title: collapse(manifest.title) || name,
        description: collapse(manifest.description),
        summary: firstSentence(manifest.description),
        schemaVersion: manifest.schemaVersion ?? 1,
        readme: `packs/${directory}/README.md`,
        useCases,
        outcome,
        maturity: manifest.catalog?.maturity ?? null,
        // v1 manifests have no distribution block: every scaffolded tool, none
        // release-qualified.
        targets: sortTools(manifest.distribution?.targets ?? adapterOrder),
        qualifiedTargets: sortTools(manifest.distribution?.qualifiedTargets ?? []),
        skills: packSkillNames(packDir, manifest),
        variants: selectedVariantIds(manifest, variants, name),
        baseInstructions: manifest.instructions
          .map((instruction) => instruction.file)
          .filter(
            (file) => base.has(file) && !existsSync(join(packDir, 'instructions', file)),
          ),
        awsServices: [],
      }
    })
    .sort((left, right) => compareText(left.name, right.name))
}

// Reads skill.yaml beside SKILL.md, in the schemaVersion 2 shape. v1 files are
// read with the resolver's own reader and presented as origin: ramp with an
// empty classification.
function readSkillMetadata(directory, name, ownerPack) {
  const path = join(directory, 'skill.yaml')
  if (!isFile(path)) return null
  const raw = parse(readFileSync(path, 'utf8'))
  if (raw?.schemaVersion === 2) {
    const findings = skillMetadataFindings(raw, { expectedName: name })
    if (findings.length > 0) throw new Error(`${path}: ${findings[0]}`)
    return skillMetadataView(raw)
  }
  return skillMetadataView(loadRampSkillMetadata(directory, { expectedName: name, ownerPack }))
}

const ORIGIN_BY_PROVENANCE = {
  ramp: 'ramp',
  upstream: 'upstream',
  'legacy-local': 'local',
  'pack-override': 'local',
}

function skillEntry(repoRoot, taxonomy, lock, name, directory, { kind, ownerPack } = {}) {
  const path = repoPath(repoRoot, directory)
  const frontmatter = readFrontmatter(join(directory, 'SKILL.md'), `${path}/SKILL.md`)
  const metadata = readSkillMetadata(directory, name, ownerPack)
  const locked = lock?.skills.get(name) ?? null
  const origin =
    metadata?.origin ?? ORIGIN_BY_PROVENANCE[kind] ?? (locked ? 'upstream' : 'local')
  const classification = Object.fromEntries(
    CLASSIFICATION_FACETS.map((facet) => [
      facet,
      orderedFacetValues(
        taxonomy,
        facet,
        metadata?.classification?.[facet] ?? [],
        `skill ${name}`,
      ),
    ]),
  )
  return {
    name,
    path,
    description: collapse(frontmatter.description),
    summary: firstSentence(frontmatter.description),
    origin,
    maturity: metadata?.maturity ?? null,
    ownerPack: metadata?.ownerPack ?? ownerPack ?? null,
    classification,
    upstream:
      origin === 'upstream' && locked
        ? {
            source: locked.source,
            repository: locked.repository,
            commit: locked.commit,
            path: locked.path,
          }
        : null,
    packs: [],
  }
}

// Every skill a pack declares is located by the skill resolver, so the
// catalogue follows the resolver's roots and precedence as they change. The
// resolver gets an empty cache: locked skills then resolve to their verified
// in-tree mirror, which also holds the skill.yaml sidecar, and the output does
// not depend on whether a cache is synchronized. Skills no pack declares are
// found beside the resolved ones, in the same shared roots.
function readSkills(repoRoot, taxonomy, packs) {
  const lock = loadSkillLock(repoRoot)
  const emptyCache = mkdtempSync(join(tmpdir(), 'ramp-catalog-cache-'))
  try {
    const resolver = createSkillResolver({
      repoRoot,
      cacheDir: emptyCache,
      allowLegacyLocal: true,
      strictProvenance: false,
    })
    const skills = new Map()
    const sharedRoots = new Set()

    for (const pack of packs) {
      for (const name of pack.skills) {
        const resolved = resolver.resolveSkill(name, {
          packDir: pack.packDir,
          packId: pack.name,
        })
        const kind = resolved.provenance.kind
        let skill = skills.get(name)
        if (!skill) {
          skill = skillEntry(repoRoot, taxonomy, lock, name, resolved.directory, {
            kind,
            ownerPack: kind === 'pack-override' ? pack.name : undefined,
          })
          skills.set(name, skill)
        } else if (skill.path !== repoPath(repoRoot, resolved.directory)) {
          throw new Error(
            `skill ${name} resolves to two directories: ${skill.path} and ${repoPath(repoRoot, resolved.directory)}`,
          )
        }
        skill.packs.push(pack.name)
        if (kind !== 'pack-override') sharedRoots.add(dirname(resolved.directory))
      }
    }

    for (const root of [...sharedRoots].sort(compareText)) {
      for (const name of listDirectoryNames(root)) {
        if (RESERVED_SKILL_SLUGS.has(name) || skills.has(name)) continue
        const directory = join(root, name)
        if (!isFile(join(directory, 'SKILL.md'))) continue
        skills.set(name, skillEntry(repoRoot, taxonomy, lock, name, directory))
      }
    }

    return [...skills.values()]
      .map((skill) => ({ ...skill, packs: [...new Set(skill.packs)].sort(compareText) }))
      .sort((left, right) => compareText(left.name, right.name))
  } finally {
    rmSync(emptyCache, { recursive: true, force: true })
  }
}

// Builds the catalogue model of one repository: the taxonomy, every pack with
// its v1 fallbacks, every skill with its origin, classification and packs, and
// the base workflow and variants with the packs that use them. Every list is
// in a fixed order, so rendering it is deterministic.
export function buildCatalog(repoRoot) {
  const root = resolve(repoRoot)
  const taxonomy = loadTaxonomy(root)
  const variants = readVariants(root)
  const base = readBaseInstructions(root)
  const packs = readPacks(root, taxonomy, variants, base)
  const skills = readSkills(root, taxonomy, packs)

  const skillsByName = new Map(skills.map((skill) => [skill.name, skill]))
  for (const pack of packs) {
    pack.awsServices = orderedFacetValues(
      taxonomy,
      'awsServices',
      pack.skills.flatMap((name) => skillsByName.get(name).classification.awsServices),
      `pack ${pack.name}`,
    )
    delete pack.packDir
  }

  const packsUsing = (predicate) =>
    packs.filter(predicate).map((pack) => pack.name)

  return {
    taxonomy: taxonomyLists(taxonomy),
    packs,
    skills,
    workflows: {
      base: [...base.entries()]
        .sort((left, right) => compareText(left[0], right[0]))
        .map(([file, path]) => ({
          file,
          path,
          packs: packsUsing((pack) => pack.baseInstructions.includes(file)),
        })),
      variants: variants
        .map((variant) => ({
          id: variant.id,
          title: variant.title,
          instruction: variant.instruction,
          whenToUse: variant.whenToUse,
          aliases: variant.aliases,
          path: variant.path,
          packs: packsUsing((pack) => pack.variants.includes(variant.id)),
        }))
        .sort((left, right) => compareText(left.id, right.id)),
    },
  }
}

// ---------------------------------------------------------------- rendering

function cell(text) {
  return collapse(String(text)).replace(/\\/g, '\\\\').replace(/\|/g, '\\|')
}

function link(label, from, target) {
  const href = posix.relative(posix.dirname(from), target) || target
  return `[${cell(label).replace(/[[\]]/g, '\\$&')}](${href})`
}

function table(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `|${headers.map(() => '---').join('|')}|`,
    ...rows.map((row) => `| ${row.join(' | ')} |`),
  ]
}

function packLinks(model, from, names) {
  if (names.length === 0) return 'none'
  const byName = new Map(model.packs.map((pack) => [pack.name, pack]))
  return names.map((name) => link(name, from, byName.get(name).readme)).join(', ')
}

function originCell(skill) {
  if (skill.origin !== 'upstream' || !skill.upstream) return skill.origin
  const { source, repository, commit, path } = skill.upstream
  const label = `${source}@${commit.slice(0, 7)}`
  const github = repository.match(/^(https:\/\/github\.com\/[^/]+\/[^/]+?)(?:\.git)?$/)
  if (!github) return `upstream (${cell(label)})`
  return `upstream ([${cell(label)}](${github[1]}/tree/${commit}/${path}))`
}

function skillRows(model, skills) {
  return skills.map((skill) => [
    link(skill.name, SKILLS_CATALOG, `${skill.path}/SKILL.md`),
    cell(skill.summary),
    originCell(skill),
    cell(skill.maturity ?? NOT_DECLARED),
    packLinks(model, SKILLS_CATALOG, skill.packs),
  ])
}

const SKILL_HEADERS = ['Skill', 'What it does', 'Origin', 'Maturity', 'Packs']

// Groups items under each taxonomy entry, in taxonomy order. Items keep their
// id order inside a group; an item appears under every entry it declares.
function facetGroups(entries, items, valuesOf) {
  return entries
    .map((entry) => ({ entry, items: items.filter((item) => valuesOf(item).includes(entry.id)) }))
    .filter((group) => group.items.length > 0)
}

function renderSkillsCatalog(model) {
  const { skills, taxonomy } = model
  const lines = [
    GENERATED_NOTICE,
    '',
    '# Skills',
    '',
    `This page lists the ${skills.length} skills in this repository. A skill is a`,
    'folder with a `SKILL.md` file that an agent tool loads when a task needs it.',
    'Each pack installs the skills it lists in its `pack.yaml`.',
    '',
    '- [By use case](#by-use-case)',
    '- [By AWS service](#by-aws-service)',
    '- [A-Z](#a-z)',
    '',
    'Origin `ramp` marks a skill written and maintained in this repository.',
    'Origin `upstream` marks a pinned copy of a skill from an upstream repository,',
    'recorded in `dependencies/skills.lock.yaml`. Origin `local` marks a skill that',
    'has not yet been adopted or locked.',
    '',
    '## By use case',
    '',
  ]
  const useCases = facetGroups(taxonomy.useCases, skills, (skill) => skill.classification.useCases)
  if (useCases.length === 0) lines.push('No skill declares a use case yet; see [A-Z](#a-z).', '')
  for (const group of useCases) {
    lines.push(`### ${group.entry.label}`, '', group.entry.description, '')
    lines.push(...table(SKILL_HEADERS, skillRows(model, group.items)), '')
  }
  const unclassified = skills.filter((skill) => skill.classification.useCases.length === 0)
  if (useCases.length > 0 && unclassified.length > 0) {
    lines.push('### Use case not declared', '')
    lines.push(...table(SKILL_HEADERS, skillRows(model, unclassified)), '')
  }

  lines.push('## By AWS service', '')
  const services = facetGroups(taxonomy.awsServices, skills, (skill) => skill.classification.awsServices)
  if (services.length === 0) lines.push('No skill declares an AWS service yet.', '')
  for (const group of services) {
    lines.push(`### ${group.entry.label}`, '')
    lines.push(...table(SKILL_HEADERS, skillRows(model, group.items)), '')
  }

  lines.push('## A-Z', '')
  lines.push(...table(SKILL_HEADERS, skillRows(model, skills)))
  return `${lines.join('\n')}\n`
}

function renderWorkflowsCatalog(model) {
  const { base, variants } = model.workflows
  const lines = [
    GENERATED_NOTICE,
    '',
    '# Workflows',
    '',
    'Every pack runs the AI-DLC workflow: a decision-gated lifecycle whose base',
    'instructions are shared by the packs. A workflow variant replaces named',
    'slots of one base instruction for a specific situation. A pack selects the',
    'variants it needs in its `pack.yaml`.',
    '',
    '## Base workflow',
    '',
  ]
  if (base.length === 0) {
    lines.push('No base instruction is defined.', '')
  } else {
    lines.push(
      ...table(
        ['Instruction', 'Packs using the shared base'],
        base.map((instruction) => [
          link(instruction.file, WORKFLOWS_CATALOG, instruction.path),
          packLinks(model, WORKFLOWS_CATALOG, instruction.packs),
        ]),
      ),
      '',
      'A pack not listed for an instruction ships its own copy in',
      '`packs/<pack>/instructions/`.',
      '',
    )
  }

  lines.push('## Variants', '')
  if (variants.length === 0) {
    lines.push('No workflow variant is defined.')
  } else {
    lines.push(
      ...table(
        ['Variant', 'Instruction', 'When to use', 'Packs'],
        variants.map((variant) => [
          variant.title === variant.id
            ? link(variant.id, WORKFLOWS_CATALOG, variant.path)
            : `${link(variant.title, WORKFLOWS_CATALOG, variant.path)} (\`${variant.id}\`)`,
          cell(variant.instruction ?? NOT_DECLARED),
          cell(variant.whenToUse || NOT_DECLARED),
          packLinks(model, WORKFLOWS_CATALOG, variant.packs),
        ]),
      ),
    )
  }
  return `${lines.join('\n')}\n`
}

function renderPacksBlock(model) {
  const { packs, taxonomy } = model
  const labels = new Map(taxonomy.awsServices.map((entry) => [entry.id, entry.label]))
  const headers = ['Pack', 'What it helps you build', 'Target tools', 'AWS services']
  const rows = (items) =>
    items.map((pack) => [
      link(pack.title, ROOT_README, pack.readme),
      cell(pack.summary),
      pack.targets
        .map((tool) => (pack.qualifiedTargets.includes(tool) ? `${tool} (release)` : tool))
        .join(', '),
      pack.awsServices.length === 0
        ? 'none declared'
        : pack.awsServices.map((id) => cell(labels.get(id))).join(', '),
    ])

  const lines = [GENERATED_NOTICE, '']
  for (const group of facetGroups(taxonomy.useCases, packs, (pack) => pack.useCases)) {
    lines.push(`### ${group.entry.label}`, '', ...table(headers, rows(group.items)), '')
  }
  const unclassified = packs.filter((pack) => pack.useCases.length === 0)
  if (unclassified.length > 0) {
    lines.push('### Use case not declared', '', ...table(headers, rows(unclassified)), '')
  }
  lines.push(
    'A target tool marked (release) has a qualified release ZIP. The AWS',
    "services are the union of the services declared by the pack's skills.",
  )
  return `${lines.join('\n')}\n`
}

// Renders the three outputs from a model. packsBlock is the text between the
// README markers, without the marker lines.
export function renderCatalog(model) {
  return {
    [SKILLS_CATALOG]: renderSkillsCatalog(model),
    [WORKFLOWS_CATALOG]: renderWorkflowsCatalog(model),
    packsBlock: renderPacksBlock(model),
  }
}

function countOf(text, marker) {
  return text.split(marker).length - 1
}

// Returns the README text with the packs block replaced, or null when the
// README has neither marker. One marker alone, a repeated marker, or END
// before START is an error.
export function replacePacksBlock(readme, block) {
  const starts = countOf(readme, PACKS_BLOCK_START)
  const ends = countOf(readme, PACKS_BLOCK_END)
  if (starts === 0 && ends === 0) return null
  const start = readme.indexOf(PACKS_BLOCK_START)
  const end = readme.indexOf(PACKS_BLOCK_END)
  if (starts !== 1 || ends !== 1 || end < start) {
    throw new Error(
      `${ROOT_README} must hold exactly one ${PACKS_BLOCK_START} followed by one ${PACKS_BLOCK_END}`,
    )
  }
  return (
    readme.slice(0, start + PACKS_BLOCK_START.length) +
    '\n' +
    block +
    readme.slice(end)
  )
}

function readOptional(path) {
  return isFile(path) ? readFileSync(path, 'utf8') : null
}

// Computes every output against the files on disk. Each entry has a path, its
// expected text (null when skipped) and a status: missing, stale, current or
// skipped (README.md without markers).
function planOutputs(repoRoot) {
  const root = resolve(repoRoot)
  const rendered = renderCatalog(buildCatalog(root))
  const outputs = [SKILLS_CATALOG, WORKFLOWS_CATALOG].map((path) => {
    const actual = readOptional(join(root, path))
    const expected = rendered[path]
    return {
      path,
      expected,
      status: actual === null ? 'missing' : actual === expected ? 'current' : 'stale',
    }
  })

  const readme = readOptional(join(root, ROOT_README))
  const expectedReadme = readme === null ? null : replacePacksBlock(readme, rendered.packsBlock)
  outputs.push({
    path: ROOT_README,
    expected: expectedReadme,
    status:
      expectedReadme === null ? 'skipped' : expectedReadme === readme ? 'current' : 'stale',
  })
  return { root, outputs }
}

// Writes skills/README.md and workflows/README.md, creating them when absent,
// and the README packs block when its markers exist. Files already current are
// not rewritten. Returns each output with status created, updated, unchanged
// or skipped.
export function writeCatalog(repoRoot) {
  const { root, outputs } = planOutputs(repoRoot)
  return outputs.map(({ path, expected, status }) => {
    if (status === 'skipped') return { path, status }
    if (status === 'current') return { path, status: 'unchanged' }
    const target = join(root, path)
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, expected, 'utf8')
    return { path, status: status === 'missing' ? 'created' : 'updated' }
  })
}

// Compares every output with what the inputs produce. problems lists each
// stale or missing output; an empty list means the catalogue is current.
export function checkCatalog(repoRoot) {
  const { outputs } = planOutputs(repoRoot)
  return {
    outputs: outputs.map(({ path, status }) => ({ path, status })),
    problems: outputs
      .filter(({ status }) => status === 'missing' || status === 'stale')
      .map(({ path, status }) => ({ path, status })),
  }
}
